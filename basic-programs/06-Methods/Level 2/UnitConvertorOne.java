package com.gla.methods;

class UnitConvertorOne {
    public static double kmToMiles(double k) { return k * 0.621371; }
    public static double milesToKm(double m) { return m * 1.60934; }
    public static double metersToFeet(double m) { return m * 3.28084; }
    public static double feetToMeters(double f) { return f * 0.3048; }
}

